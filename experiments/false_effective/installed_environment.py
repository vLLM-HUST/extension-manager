#!/usr/bin/env python3
"""Fingerprint installed venv bytes for a non-container deployment candidate.

This records the venv, not system CANN/driver libraries or a compatibility
decision. Generated bytecode is excluded because imports may create it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def fingerprint(root: Path) -> dict[str, object]:
    root = root.absolute()
    config = root / "pyvenv.cfg"
    python = root / "bin" / "python"
    site_roots = sorted((root / "lib").glob("python*/site-packages"))
    if not config.is_file() or not python.is_file() or len(site_roots) != 1:
        raise ValueError("expected one complete Python virtual environment")
    if "include-system-site-packages = false" not in config.read_text().lower():
        raise ValueError("system site packages must be disabled")

    site = site_roots[0]
    if site.is_symlink():
        raise ValueError("site-packages directory must not be a symlink")
    for direct_url in site.glob("*.dist-info/direct_url.json"):
        metadata = json.loads(direct_url.read_text())
        if metadata.get("dir_info", {}).get("editable") is True:
            raise ValueError(f"editable distribution: {direct_url.parent.name}")

    entries: list[tuple[str, str, int]] = []
    for base in (root / "bin", site):
        for path in sorted(base.rglob("*")):
            if "__pycache__" in path.parts or path.suffix == ".pyc":
                continue
            if path.is_symlink() and base == site:
                raise ValueError(f"site-packages symlink: {path.relative_to(root)}")
            if not path.is_file():
                continue
            resolved = path.resolve(strict=True)
            if path.is_symlink() and not resolved.is_file():
                raise ValueError(f"non-file venv link: {path.relative_to(root)}")
            entries.append(
                (str(path.relative_to(root)), _sha256(path), path.stat().st_size)
            )
    entries.append(("pyvenv.cfg", _sha256(config), config.stat().st_size))
    entries.sort()
    digest = hashlib.sha256()
    for name, file_digest, size in entries:
        digest.update(f"{name}\0{file_digest}\0{size}\n".encode())
    return {
        "schema": "ecpa-installed-environment-fingerprint/v1",
        "environment_digest": f"sha256:{digest.hexdigest()}",
        "python_binary_sha256": _sha256(python),
        "file_count": len(entries),
        "total_bytes": sum(size for _, _, size in entries),
        "site_packages": str(site.relative_to(root)),
        "exclusions": ["__pycache__", "*.pyc"],
        "scope": "venv-installed-bytes-only; excludes CANN, driver, model and host OS",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("venv", type=Path)
    args = parser.parse_args()
    print(json.dumps(fingerprint(args.venv), sort_keys=True, separators=(",", ":")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
